// Run this to clean up old broken sitemap files from public/
// Command: node scripts/cleanup-old-sitemaps.js

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const PUBLIC_DIR = path.join(__dirname, '../public');

const filesToDelete = [
    'sitemap-bitsat.xml',
    'sitemap-blogs.xml',
    'sitemap-class-6.xml',
    'sitemap-class-7.xml',
    'sitemap-class-8.xml',
    'sitemap-class-9.xml',
    'sitemap-class-10.xml',
    'sitemap-class-11.xml',
    'sitemap-class-12.xml',
    'sitemap-clat.xml',
    'sitemap-core.xml',
    'sitemap-gate.xml',
    'sitemap-jee-advanced.xml',
    'sitemap-jee-mains.xml',
    'sitemap-main.xml',
    'sitemap-neet.xml',
    'sitemap-questions-batch1.xml',
    'sitemap-topics.xml',
    'sitemap-upsc.xml',
    'sitemap.xml', // The old index — generate-sitemap.js creates the new one in dist/
];

let deleted = 0;
for (const file of filesToDelete) {
    const filePath = path.join(PUBLIC_DIR, file);
    if (fs.existsSync(filePath)) {
        fs.unlinkSync(filePath);
        console.log(`🗑️  Deleted: ${file}`);
        deleted++;
    } else {
        console.log(`⏭️  Skipped (not found): ${file}`);
    }
}

console.log(`\n✅ Cleaned up ${deleted} old sitemap files from public/`);
console.log(`ℹ️  The new single sitemap.xml will be generated by generate-sitemap.js into dist/ during build.`);
